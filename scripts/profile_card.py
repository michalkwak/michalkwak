# ---------------------------------------------------------------- live stats

def api(path, body=None):
    headers = {"Accept": "application/vnd.github+json", "User-Agent": USER}
    if TOKEN:
        headers["Authorization"] = f"Bearer {TOKEN}"
    data = json.dumps(body).encode() if body else None
    req = urllib.request.Request(path if path.startswith("http") else API + path, data, headers)
    with urllib.request.urlopen(req, timeout=30) as r:
        return json.load(r)


def count_commits(created):
    if TOKEN:
        try:
            return count_contributions(created)
        except (KeyError, TypeError, OSError):
            pass
    return api(f"/search/commits?q=author:{USER}")["total_count"]  # fallback: public commits found by search


def count_contributions(created):
    query = ("query($u:String!,$f:DateTime!,$t:DateTime!){user(login:$u)"
             "{contributionsCollection(from:$f,to:$t){totalCommitContributions}}}")
    now, start, total = datetime.now(timezone.utc), created, 0
    while start < now:  # contributionsCollection spans at most one year
        end = min(start + timedelta(days=365), now)
        res = api("/graphql", {"query": query, "variables": {
            "u": USER, "f": start.isoformat(), "t": end.isoformat()}})
        total += res["data"]["user"]["contributionsCollection"]["totalCommitContributions"]
        start = end
    return total


def fetch_stats():
    user = api(f"/users/{USER}")
    repos = [r for r in api(f"/users/{USER}/repos?per_page=100&type=owner") if not r["fork"]]
    langs = {}  # language -> (repos using it, total bytes); ranked by repo count so one big project can't dominate
    for repo in repos:
        for lang, size in api(repo["languages_url"]).items():
            if lang in IGNORED_LANGS:
                continue
            count, total = langs.get(lang, (0, 0))
            langs[lang] = (count + 1, total + size)
    created = datetime.fromisoformat(user["created_at"].replace("Z", "+00:00"))
    now = datetime.now(timezone.utc)
    months = (now.year - created.year) * 12 + now.month - created.month - (now.day < created.day)
    return {
        "repos": user["public_repos"],
        "commits": count_commits(created),
        "followers": user["followers"],
        "age": f"{months // 12}y {months % 12}m" if months >= 12 else f"{months}m",
        "langs": [lang for lang, _ in sorted(langs.items(), key=lambda kv: kv[1], reverse=True)],
        "updated": f"{now.day} {now:%b %Y}",
    }


# ---------------------------------------------------------------- glucose trace (illustrative)

CTRL = [142, 138, 135, 140, 156, 178, 192, 196, 186, 166, 140, 112, 88]  # every 15 min, last 3 h
FORECAST = [82, 77, 72, 67, 62, 58]  # next 30 min, every 5 min


def catmull(t):
    i = min(int(t // 15), len(CTRL) - 2)
    u = t / 15 - i
    p0, p1, p2, p3 = CTRL[max(i - 1, 0)], CTRL[i], CTRL[i + 1], CTRL[min(i + 2, len(CTRL) - 1)]
    return 0.5 * (2 * p1 + (p2 - p0) * u + (2 * p0 - 5 * p1 + 4 * p2 - p3) * u * u
                  + (3 * p1 - p0 - 3 * p2 + p3) * u ** 3)


def readings():
    rng = random.Random(7)  # fixed seed: sensor-like jitter that stays the same every run
    return [(t, catmull(t) + (rng.uniform(-2.5, 2.5) if t < 180 else 0)) for t in range(0, 181, 5)]


# ---------------------------------------------------------------- drawing

W, H, PAD = 900, 866, 40
MARGIN = 28                  # transparent space below the card, before the social buttons
X0, X1 = PAD, 800            # plot x range (0 .. 210 min)
Y0, Y1 = 330, 520            # plot y range (300 .. 40 mg/dL)


def gx(t): return X0 + t * (X1 - X0) / 210
def gy(g): return Y1 - (g - 40) * (Y1 - Y0) / 260


def icon(name, x, y, size, fill):
    return (f'<g transform="translate({x:.1f},{y:.1f}) scale({size / 24:.4f})">'
            f'<path d="{ICONS[name]}" fill="{fill}"/></g>')


